#!/usr/bin/env python3
"""Emit allowlisted LibraryImport declarations from the checked-in C header.

The full header is far larger than this scaffold. Regeneration rewrites only
the functions listed below, and fails if a signature uses a type this mapping
does not know. Run from anywhere:

    python3 scripts/gen_dotnet_bindings.py
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HEADER = ROOT / "crates/libitofin-ffi/include/itofin.h"
OUT = ROOT / "sdk/dotnet/Itofin/Native/NativeMethods.g.cs"

# Representative slice: context ownership, dates, one analytic pricer,
# Black implied vol, and the string/array helpers those wrappers use.
ALLOW = (
    "itofin_abi_version",
    "itofin_version",
    "itofin_context_new",
    "itofin_context_free",
    "itofin_handle_release",
    "itofin_date_new",
    "itofin_date_shift",
    "itofin_settings_new",
    "itofin_settings_set_evaluation_date",
    "itofin_day_counter_new",
    "itofin_time_name",
    "itofin_black_scholes_new",
    "itofin_option_new",
    "itofin_option_set_engine",
    "itofin_option_value",
    "itofin_black_formula_implied_std_dev",
    "itofin_black_formula_implied_volatility",
    "itofin_bermudan_exercise_new",
    "itofin_bermudan_exercise_dates",
)

PRIMITIVES = {
    "void": "void",
    "int32_t": "int",
    "uint32_t": "uint",
    "int64_t": "long",
    "uint64_t": "ulong",
    "size_t": "nuint",
    "double": "double",
    "ItofinReal": "double",
    "uint8_t": "byte",
    "char": "byte",
}
KEYWORDS = {"out", "in", "ref", "params", "fixed", "event", "object", "base", "string"}


def strip_header(text: str) -> str:
    text = re.sub(r"/\*.*?\*/", " ", text, flags=re.S)
    text = re.sub(r"^\s*#.*$", " ", text, flags=re.M)
    return text


def cdecl(text: str, name: str) -> tuple[str, str]:
    idx = text.find(f"{name}(")
    if idx < 0:
        sys.exit(f"missing declaration: {name}")
    start = max(text.rfind(";", 0, idx), text.rfind("}", 0, idx)) + 1
    end = text.find(");", idx)
    if end < 0:
        sys.exit(f"unterminated declaration: {name}")
    return re.sub(r"\s+", " ", text[start:idx]).strip(), text[idx + len(name) + 1 : end]


def split_params(params: str) -> list[str]:
    body = params.strip()
    if body in ("", "void"):
        return []
    parts: list[str] = []
    buf = ""
    depth = 0
    for ch in body:
        if ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
        if ch == "," and depth == 0:
            parts.append(buf.strip())
            buf = ""
        else:
            buf += ch
    if buf.strip():
        parts.append(buf.strip())
    return parts


def cs_type(raw: str, where: str) -> str:
    text = raw.replace("const ", "").replace("struct ", "")
    text = re.sub(r"\s+", "", text)
    stars = text.count("*")
    base = text.replace("*", "")
    if base == "ItofinContext":
        mapped = "nint"
    elif base == "ItofinError":
        mapped = "ItofinError"
    elif base in PRIMITIVES:
        mapped = PRIMITIVES[base]
    else:
        sys.exit(f"unmapped type {raw!r} in {where}")
    if stars > 1 and base != "ItofinContext":
        sys.exit(f"unsupported pointer depth in {where}: {raw}")
    if base == "ItofinContext":
        return "nint*" if stars == 2 else "nint"
    return mapped + ("*" * stars)


def emit(decls: list[tuple[str, str, list[str]]]) -> str:
    lines = [
        "// <auto-generated>",
        "// Generated by scripts/gen_dotnet_bindings.py from crates/libitofin-ffi/include/itofin.h.",
        "// Do not edit. Regenerate with: python3 scripts/gen_dotnet_bindings.py",
        "using System.Runtime.InteropServices;",
        "",
        "namespace Itofin.Native;",
        "",
        "[StructLayout(LayoutKind.Sequential)]",
        "internal unsafe struct ItofinError",
        "{",
        "    internal int Code;",
        "    internal fixed byte Message[1024];",
        "}",
        "",
        "internal static unsafe partial class NativeMethods",
        "{",
        '    private const string Lib = "itofin_ffi";',
        "",
    ]
    for ret, name, args in decls:
        lines.append(f"    [LibraryImport(Lib)] internal static partial {ret} {name}({', '.join(args)});")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    text = strip_header(HEADER.read_text())
    decls = []
    for name in ALLOW:
        ret_c, params = cdecl(text, name)
        args = []
        for param in split_params(params):
            match = re.match(r"^(.*?)([A-Za-z_]\w*)$", re.sub(r"\s+", " ", param).strip())
            if not match:
                sys.exit(f"bad parameter {param!r} in {name}")
            pname = match.group(2)
            if pname in KEYWORDS:
                pname = f"@{pname}"
            args.append(f"{cs_type(match.group(1), name)} {pname}")
        decls.append((cs_type(ret_c, name), name, args))
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(emit(decls))
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
